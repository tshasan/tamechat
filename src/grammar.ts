const inlineSimple = ['strong', 'em', 'sub', 'sup', 'del', 'kbd', 'mark', 'small'];
const asideKinds = ['note', 'tip', 'warn'];
const omissible = new Set(['p', 'li', 'td', 'th', 'tr', 'thead', 'tbody', 'dt', 'dd']);

const widgetTags = [
  'div', 'span', 'p', 'h2', 'h3', 'h4', 'section', 'header', 'footer',
  'label', 'input', 'button', 'output', 'select', 'option', 'textarea',
  'form', 'fieldset', 'legend', 'progress', 'meter', 'canvas',
  'table', 'thead', 'tbody', 'tr', 'th', 'td', 'ul', 'ol', 'li',
  'strong', 'em', 'code', 'pre', 'small', 'br', 'hr',
  'details', 'summary', 'dialog',
  'svg', 'g', 'path', 'circle', 'rect', 'line', 'polyline', 'polygon',
  'ellipse', 'text',
];

const alt = (words: string[]): string => words.map((w) => `"${w}"`).join(' | ');

export interface GrammarVariant {
  compact: boolean;
  widgets: boolean;
}

export const variants: GrammarVariant[] = [false, true].flatMap((compact) => [false, true].map((widgets) => ({ compact, widgets })));

export function grammarName({ compact, widgets }: GrammarVariant): string {
  return `${compact ? 'compact' : 'strict'}${widgets ? '+widgets' : ''}.gbnf`;
}

export function buildGrammar({ compact, widgets }: GrammarVariant): string {
  const E = (tag: string): string => (compact && omissible.has(tag) ? `"</${tag}>"?` : `"</${tag}>"`);
  const role = compact ? '(" role=\\"note\\"")?' : '" role=\\"note\\""';
  const buttonType = compact ? '(" type=\\"button\\"")?' : '" type=\\"button\\""';
  const blockAlts = ['p', 'heading', 'ul', 'ol', 'blockquote', 'pre', 'hr', 'table', 'details', 'dl', 'aside', 'menu'];
  if (widgets) blockAlts.push('widget');
  const name = `${compact ? 'compact' : 'strict'}${widgets ? ' with widgets' : ''}`;

  let g = `# HTML-subset answer grammar (${name}), generated by bin/grammar.ts
root ::= ws block (ws block)* ws

ws ::= "\\n"{0,2}

block ::= ${blockAlts.join(' | ')}

phr  ::= tchar | entity | inline
inline ::= simple-inline | code | a | br | abbr
simple-inline ::= ${inlineSimple.map((t) => `"<${t}>" phr+ "</${t}>"`).join(' | ')}
code ::= "<code>" [ \\t]* cvis cchar* "</code>"
br   ::= "<br>"
abbr ::= "<abbr title=\\"" attr-char+ "\\">" (tchar | entity)+ "</abbr>"
a    ::= "<a href=\\"" url "\\">" (tchar | entity | code)+ "</a>"

url  ::= ("https://" | "mailto:" | "#") url-char+
url-char  ::= [^\\x22<>'\` \\t\\n]
attr-char ::= [^\\x22<>&\\n]

tchar  ::= [^<>&]
cchar  ::= [^<>&\\n] | entity
cvis   ::= [^<>&\\n \\t] | entity
entity ::= "&" ("amp" | "lt" | "gt" | "quot" | "apos" | "nbsp" | "#" [0-9]{2,6}) ";"

p       ::= "<p>" phr+ ${E('p')}
heading ::= "<h2>" phr+ "</h2>" | "<h3>" phr+ "</h3>" | "<h4>" phr+ "</h4>"
hr      ::= "<hr>"

ul ::= "<ul>" ws (li ws)+ "</ul>"
ol ::= "<ol" (" start=\\"" [0-9]{1,4} "\\"")? ">" ws (li ws)+ "</ol>"
li ::= "<li>" (phr | ul | ol | p | pre)+ ${E('li')}

blockquote ::= "<blockquote>" ws (block ws)+ "</blockquote>"

pre  ::= "<pre><code" (" class=\\"language-" lang "\\"")? ">" pchar+ "</code></pre>"
lang ::= [a-z0-9+#_-]{1,20}
pchar ::= [^<&] | entity

table   ::= "<table>" ws caption? thead? "<tbody>" ws (tr ws)+ ${E('tbody')} ws "</table>"
caption ::= "<caption>" phr+ "</caption>" ws
thead   ::= "<thead>" ws (tr ws)+ ${E('thead')} ws
tr      ::= "<tr>" ws (cell ws)+ ${E('tr')}
cell    ::= th | td
th      ::= "<th" span? (" scope=\\"" ("col" | "row") "\\"")? ">" phr* ${E('th')}
td      ::= "<td" span? ">" phr* ${E('td')}
span    ::= " colspan=\\"" [1-9] "\\"" | " rowspan=\\"" [1-9] "\\"" | " colspan=\\"" [1-9] "\\" rowspan=\\"" [1-9] "\\""

details ::= "<details>" ws "<summary>" phr+ "</summary>" ws (block ws)+ "</details>"

dl ::= "<dl>" ws (dt-group ws)+ "</dl>"
dt-group ::= ("<dt>" phr+ ${E('dt')} ws)+ ("<dd>" phr+ ${E('dd')} ws)+

aside ::= "<aside class=\\"" (${alt(asideKinds)}) "\\"" ${role} ">" ws (block ws)+ "</aside>"

menu ::= "<menu>" ws (choice ws)+ "</menu>"
choice ::= "<li><button" ${buttonType} " value=\\"" attr-char+ "\\">" (tchar | entity)+ "</button></li>"
`;
  if (widgets) {
    g += `
widget ::= "<template data-widget title=\\"" attr-char+ "\\">" w-item+ "</template>"
w-item ::= [^<] | w-open | w-close | w-script | w-style
w-open  ::= "<" w-tag w-attr* [ \\t\\n]? "/"? ">"
w-close ::= "</" w-tag ">"
w-tag   ::= ${alt(widgetTags)}
w-attr  ::= [ \\t\\n]+ [a-zA-Z_:] [a-zA-Z0-9_:.-]* ("=\\"" [^\\x22]* "\\"")?
w-script ::= "<script>" ([^<] | "<" [^/])* "</script>"
w-style  ::= "<style>" [^<]* "</style>"
`;
  }
  return g;
}
