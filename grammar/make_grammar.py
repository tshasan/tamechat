#!/usr/bin/env python3
"""Generate the GBNF grammars for answers in the HTML subset.

    python3 grammar/make_grammar.py

Writes next to this file:
  strict.gbnf            every end tag written
  compact.gbnf           accepts strict documents AND compact ones (the optional end tags and the
                         role/type attributes may be left out). It allows the omissions but does
                         not force them: forcing them on a model that was not trained for it
                         makes it stop early or loop (see findings/).
  strict+widgets.gbnf    plus <template data-widget> blocks
  compact+widgets.gbnf

The element and attribute lists must match spec/subset.json; a Go test checks that. The
generated files are committed, so you only need Python to change the grammar.

Design rules:
  * every element is a real HTML element, no custom elements
  * attribute values are fixed strings or tightly patterned
  * phrasing content is parsed one character at a time, so the grammar is unambiguous and
    llama.cpp keeps few parse stacks (fast sampling)
"""
from pathlib import Path

HERE = Path(__file__).parent

INLINE_SIMPLE = ["strong", "em", "sub", "sup", "del", "kbd", "mark", "small"]
ASIDE_KINDS = ["note", "tip", "warn"]
# End tags HTML lets an author omit (the parser puts them back). Same list as spec/subset.json.
OMITTABLE = {"p", "li", "td", "th", "tr", "thead", "tbody", "dt", "dd"}

# Tags allowed inside a widget's markup. The widget is sandboxed, so this keeps the model
# on task rather than guarding anything.
WIDGET_TAGS = [
    "div", "span", "p", "h2", "h3", "h4", "section", "header", "footer",
    "label", "input", "button", "output", "select", "option", "textarea",
    "form", "fieldset", "legend", "progress", "meter", "canvas",
    "table", "thead", "tbody", "tr", "th", "td", "ul", "ol", "li",
    "strong", "em", "code", "pre", "small", "br", "hr",
    "details", "summary", "dialog",
    "svg", "g", "path", "circle", "rect", "line", "polyline", "polygon",
    "ellipse", "text",
]


def alt(words):
    return " | ".join(f'"{w}"' for w in words)


def build(widgets: bool, compact: bool) -> str:
    def E(tag):  # an end tag: required, or optional in the compact grammar
        return f'"</{tag}>"?' if compact and tag in OMITTABLE else f'"</{tag}>"'

    ROLE = '(" role=\\"note\\"")?' if compact else '" role=\\"note\\""'
    BTYPE = '(" type=\\"button\\"")?' if compact else '" type=\\"button\\""'
    block_alts = ["p", "heading", "ul", "ol", "blockquote", "pre", "hr",
                  "table", "details", "dl", "aside", "menu"]
    if widgets:
        block_alts.append("widget")
    name = ("compact" if compact else "strict") + (" with widgets" if widgets else "")

    g = f"""# HTML-subset answer grammar ({name}).
# Generated by make_grammar.py; edit that file, not this one.

root ::= ws block (ws block)* ws

# Between blocks: at most two newlines, no indentation. Zero is allowed, which is what
# compact documents use.
ws ::= "\\n"{{0,2}}

block ::= {" | ".join(block_alts)}

# ---------- phrasing (inline) content ----------
phr  ::= tchar | entity | inline
inline ::= simple-inline | code | a | br | abbr
simple-inline ::= {" | ".join(f'"<{t}>" phr+ "</{t}>"' for t in INLINE_SIMPLE)}
# Inline code: one line, at least one visible character (stops empty-tag loops).
code ::= "<code>" [ \\t]* cvis cchar* "</code>"
br   ::= "<br>"
abbr ::= "<abbr title=\\"" attr-char+ "\\">" (tchar | entity)+ "</abbr>"
a    ::= "<a href=\\"" url "\\">" (tchar | entity | code)+ "</a>"

url  ::= ("https://" | "mailto:" | "#") url-char+
url-char  ::= [^\\x22<>'` \\t\\n]
attr-char ::= [^\\x22<>&\\n]

tchar  ::= [^<>&]
cchar  ::= [^<>&\\n] | entity
cvis   ::= [^<>&\\n \\t] | entity
entity ::= "&" ("amp" | "lt" | "gt" | "quot" | "apos" | "nbsp" | "#" [0-9]{{2,6}}) ";"

# ---------- blocks ----------
p       ::= "<p>" phr+ {E('p')}
heading ::= "<h2>" phr+ "</h2>" | "<h3>" phr+ "</h3>" | "<h4>" phr+ "</h4>"
hr      ::= "<hr>"

ul ::= "<ul>" ws (li ws)+ "</ul>"
ol ::= "<ol" (" start=\\"" [0-9]{{1,4}} "\\"")? ">" ws (li ws)+ "</ol>"
li ::= "<li>" (phr | ul | ol | p | pre)+ {E('li')}

blockquote ::= "<blockquote>" ws (block ws)+ "</blockquote>"

# Raw > is fine inside a code block; < and & are not.
pre  ::= "<pre><code" (" class=\\"language-" lang "\\"")? ">" pchar+ "</code></pre>"
lang ::= [a-z0-9+#_-]{{1,20}}
pchar ::= [^<&] | entity

table   ::= "<table>" ws caption? thead? "<tbody>" ws (tr ws)+ {E('tbody')} ws "</table>"
caption ::= "<caption>" phr+ "</caption>" ws
thead   ::= "<thead>" ws (tr ws)+ {E('thead')} ws
tr      ::= "<tr>" ws (cell ws)+ {E('tr')}
cell    ::= th | td
th      ::= "<th" span? (" scope=\\"" ("col" | "row") "\\"")? ">" phr* {E('th')}
td      ::= "<td" span? ">" phr* {E('td')}
span    ::= " colspan=\\"" [1-9] "\\"" | " rowspan=\\"" [1-9] "\\"" | " colspan=\\"" [1-9] "\\" rowspan=\\"" [1-9] "\\""

details ::= "<details>" ws "<summary>" phr+ "</summary>" ws (block ws)+ "</details>"

dl ::= "<dl>" ws (dt-group ws)+ "</dl>"
dt-group ::= ("<dt>" phr+ {E('dt')} ws)+ ("<dd>" phr+ {E('dd')} ws)+

aside ::= "<aside class=\\"" ({alt(ASIDE_KINDS)}) "\\"" {ROLE} ">" ws (block ws)+ "</aside>"

# Choices the user can click; the page sends the value back as a message.
menu ::= "<menu>" ws (choice ws)+ "</menu>"
choice ::= "<li><button" {BTYPE} " value=\\"" attr-char+ "\\">" (tchar | entity)+ "</button></li>"
"""
    if widgets:
        g += f"""
# ---------- widgets ----------
# Contents are NOT rendered in the page: the client moves them into a sandboxed iframe
# (allow-scripts, opaque origin, strict CSP). Markup inside is not balance-checked; the
# sandbox is the safety boundary.
widget ::= "<template data-widget title=\\"" attr-char+ "\\">" w-item+ "</template>"
w-item ::= [^<] | w-open | w-close | w-script | w-style
w-open  ::= "<" w-tag w-attr* [ \\t\\n]? "/"? ">"
w-close ::= "</" w-tag ">"
w-tag   ::= {alt(WIDGET_TAGS)}
w-attr  ::= [ \\t\\n]+ [a-zA-Z_:] [a-zA-Z0-9_:.-]* ("=\\"" [^\\x22]* "\\"")?
w-script ::= "<script>" ([^<] | "<" [^/])* "</script>"
w-style  ::= "<style>" [^<]* "</style>"
"""
    return g


if __name__ == "__main__":
    for compact in (False, True):
        for widgets in (False, True):
            fname = ("compact" if compact else "strict") + ("+widgets" if widgets else "") + ".gbnf"
            (HERE / fname).write_text(build(widgets, compact))
    print("wrote strict.gbnf, strict+widgets.gbnf, compact.gbnf, compact+widgets.gbnf")
